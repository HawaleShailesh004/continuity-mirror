// Result-check evaluation (elite-plan B3). Measures every genuine YouCam result in public/demo with the same
// on-device check the app runs (face geometry + hair colour), and writes docs/EVAL.md. Spends no units.
//
//   pnpm dev            (the harness page /dev/check only exists in development)
//   pnpm eval           uses http://localhost:3000, or: pnpm eval -- --url http://localhost:3001
//
// The numbers in the "live repair" appendix were measured by hand against the live API on 30 Oct 2026
// (11 units) and are kept here as data so they are reviewed with the rest; the rest is regenerated.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { chromium } from "@playwright/test";
import { THRESHOLDS } from "@/lib/client/check/judge";

type Row = { person: string; key: string; kind: string; drift: number | null; baselineHex: string | null; resultHex: string | null; deltaE: number | null; coverage: number | null };

const arg = process.argv.indexOf("--url");
const base = arg > 0 ? process.argv[arg + 1]! : "http://localhost:3000";

const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? (s.length % 2 ? s[(s.length - 1) / 2]! : (s[s.length / 2 - 1]! + s[s.length / 2]!) / 2) : NaN;
};
const f = (n: number, d = 1) => (Number.isFinite(n) ? n.toFixed(d) : "n/a");
const pct = (a: number, b: number) => (b ? `${Math.round((100 * a) / b)} %` : "n/a");

const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(`${base}/dev/check`, { waitUntil: "domcontentloaded", timeout: 120_000 });
await page.waitForFunction(() => (window as unknown as { __checkDone?: boolean }).__checkDone === true, null, { timeout: 280_000 });
const rows: Row[] = await page.evaluate(() => (window as unknown as { __checkRows: Row[] }).__checkRows);
await browser.close();

const results = rows.filter((r) => r.kind !== "control");
const controls = rows.filter((r) => r.kind === "control");
const drifts = results.map((r) => r.drift).filter((d): d is number => d !== null);
const controlDrifts = controls.map((r) => r.drift).filter((d): d is number => d !== null);

// Own-colour routes with enough hair to measure: the ones the colour check applies to.
const own = results.filter((r) => r.kind.endsWith(":own") && r.deltaE !== null && (r.coverage ?? 0) >= THRESHOLDS.minHairCoverage);
const ownShort = results.filter((r) => r.kind.endsWith(":own") && (r.coverage ?? 0) < THRESHOLDS.minHairCoverage);
const intended = results.filter((r) => (r.kind.endsWith(":preset") || r.kind.startsWith("colour")) && r.deltaE !== null);
const ownDE = own.map((r) => r.deltaE!);
const drifted = own.filter((r) => r.deltaE! > THRESHOLDS.colourDrift);

const table = (rs: Row[]) =>
  ["| Person | Result | Face drift | Baseline hair | Result hair | ΔE | Hair share |", "|---|---|---:|---|---|---:|---:|"]
    .concat(rs.map((r) => `| ${r.person} | ${r.key} | ${f(r.drift ?? NaN, 3)} | ${r.baselineHex ?? "–"} | ${r.resultHex ?? "–"} | ${f(r.deltaE ?? NaN)} | ${f((r.coverage ?? NaN) * 100, 0)} % |`))
    .join("\n");

// Hand-measured against the live API, 30 Oct 2026. Source: one live "Closest to me" result for Meera (ΔE 4.5), repaired with one Hair Color pass each.
const LIVE_REPAIRS: [string, string, string][] = [
  ["#211B13", "target as measured", "7.4 (outlier), 1.5, 1.9"],
  ["#221C14", "target, one step off", "1.8"],
  ["#2A1D18", "the user's tapped colour", "4.7"],
  ["#14100B", "a step darker than target", "0.8"],
  ["#151009, #16110A, #15110B", "a step darker than target (3 repeats)", "0.9, 0.8, 0.9"],
  ["#0F0C09", "two steps darker", "2.3"],
];

const md = `# Result check: evaluation

Generated by \`pnpm eval\` (scripts/eval-check.ts) on ${new Date().toISOString().slice(0, 10)}. It measures the ${results.length} genuine YouCam results shipped in \`public/demo\` with the same code the app runs on a user's device (\`lib/client/check\`). Spends no units. Thresholds live in \`lib/client/check/judge.ts\`.

The face check is a geometry check: it notices when an edit moved or swapped the face, not a subtle change, and it is not identity verification. The check asks two questions and never rates anyone: did the face keep its geometry (eyes, nose, mouth), and, when the route promised the user's own colour, is the hair still that colour (CIEDE2000 between the baseline's and the result's hair, measured on a hair mask).

## Summary

| Question | Result |
|---|---|
| Face geometry kept (drift ≤ ${THRESHOLDS.faceChanged}) | **${drifts.filter((d) => d <= THRESHOLDS.faceChanged).length} of ${drifts.length}** genuine results (${pct(drifts.filter((d) => d <= THRESHOLDS.faceChanged).length, drifts.length)}); worst drift ${f(Math.max(...drifts), 3)}, median ${f(median(drifts), 3)} |
| Face check catches a different person in the same pose (negative control) | **${controlDrifts.filter((d) => d > THRESHOLDS.faceChanged).length} of ${controlDrifts.length}** swapped pairs flagged; smallest drift ${f(Math.min(...controlDrifts), 3)} against a worst genuine ${f(Math.max(...drifts), 3)} (threshold ${THRESHOLDS.faceChanged}, so the margin is about ${f(Math.min(...controlDrifts) / THRESHOLDS.faceChanged, 1)}× above and ${f(THRESHOLDS.faceChanged / Math.max(...drifts), 1)}× below) |
| Own-colour results whose hair stayed the user's colour (ΔE ≤ ${THRESHOLDS.colourDrift}) | **${own.length - drifted.length} of ${own.length}** (${pct(own.length - drifted.length, own.length)}); median ΔE ${f(median(ownDE))} |
| Own-colour results that drifted and would be repaired (1 unit each) | **${drifted.length} of ${own.length}** (${pct(drifted.length, own.length)}); worst ΔE ${f(Math.max(...ownDE))} |
| Deliberate colour changes read as changes | smallest ΔE ${f(Math.min(...intended.map((r) => r.deltaE!)))} over ${intended.length} results, against a worst own-colour drift of ${f(Math.max(...ownDE))} |
| Results too short-haired to measure colour honestly (hair < ${THRESHOLDS.minHairCoverage * 100} % of the image) | ${ownShort.length}; the colour check is skipped for these and says nothing |

## Live repair (30 Oct 2026, 11 units, measured by hand)

One live "Closest to me" result for Meera had drifted (ΔE 4.5 from her own hair). The same result was recoloured by one Hair Color pass, asking for different colours:

| Requested colour | What it is | ΔE after the pass |
|---|---|---|
${LIVE_REPAIRS.map(([hex, what, de]) => `| ${hex} | ${what} | ${de} |`).join("\n")}

Reading: asking for exactly the baseline's colour lands close (ΔE 1.5–1.9) but one run in ten came back worse (7.4); asking a step *past* the target, away from the drift, landed at ΔE 0.8–0.9 four times in four. The app therefore asks for \`target + 0.5 × (target − result)\` in CIELAB (\`repairColour\`) and, because a run can still come back worse, measures the repaired image and puts the first one back unless it is closer (\`afterRepair\`). End to end on the live API the same afternoon: ΔE 4.6 → 1.28, face drift unchanged (0.004).

Earlier, the same afternoon, on the stored demo results (6 units): one pass with the baseline's measured colour took Daniel's "easier" (ΔE 7.0) and "variant 1" (6.8) to 1.8, and Meera's "closest" (5.4) and "variant 1" (4.8) to 1.2 and 0.9. With the tapped colour (Meera's #2A1D18 / the wrong person's hex for Daniel) the same pass only reached 4.9 and 6.5.

## Every measurement

${table(results)}

### Negative control (a baseline against another person's result)

${table(controls)}
`;

writeFileSync(join(import.meta.dirname, "..", "docs", "EVAL.md"), md);
console.log(`docs/EVAL.md written: ${results.length} results, ${controls.length} controls, ${drifted.length}/${own.length} drifted`);
